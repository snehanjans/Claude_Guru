const getColors = (mode: PaletteMode, formattedArray?: boolean) => {
  const colorInfo = colors[mode] || colors['light']

  if (!formattedArray) {
    return colorInfo
  }

  // break down color into array based on theme
  const colorArr = {} as any
  Object.keys(colorInfo).forEach((col) => {
    const nestedColors = Object.keys(colorInfo[col])
    nestedColors.forEach((nColor) => {
      colorArr[`--${col}-${nColor}`] = colorInfo[col][nColor]
    })
  })

  return colorArr
}

export default getColors
